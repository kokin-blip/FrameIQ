use frameiq_contracts::*;
use ts_rs::TS;
fn main() {
    let mut out = String::from("// Generated by frameiq-contracts. Do not edit.\n");
    macro_rules! add { ($($t:ty),*) => { $(out.push_str("export ");out.push_str(&<$t>::decl());out.push('\n');)* }; }
    add!(
        TimestampOrigin,
        FrameRefV1,
        IndexedFrame,
        StreamInfo,
        MediaMetadata,
        Project,
        SourceSummary,
        FrameView,
        JobStatus,
        AppError,
        JobEvent,
        ExportFormat,
        ColorMode,
        ColorPolicyV2,
        ExportOptions,
        Selection,
        ExportItemV1,
        ExportPlanV1,
        ExportAttemptSummaryV1,
        QualityMetricsV1,
        QualityFrameV1,
        RankingConfigV1,
        RecommendationV1,
        RecommendationSetV1,
        TensorSpecV1,
        ModelManifestV1,
        ModelInstallationV1,
        HardwareProfileV1,
        ModelBenchmarkV1,
        LocalRuntimeModelV1,
        LocalRuntimeReportV1,
        PresetV1,
        RegionRectV1,
        GuidedRegionV1,
        LandmarkV1,
        FaceDetectionV1,
        FaceResultV1,
        FaceFrameV1,
        PersonDetectionV1,
        PersonResultV1,
        PoseLandmarkV1,
        PoseDetectionV1,
        PoseResultV1,
        PersonFrameV1,
        PoseFrameV1,
        SubjectReferenceV1,
        SubjectChoiceV1,
        PresetExecutionV1,
        TrackObservationV1,
        SubjectTrackV1,
        PresetResultV1
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/desktop/src/contracts.ts");
    if std::env::args().any(|a| a == "--check") {
        assert_eq!(
            std::fs::read_to_string(path)
                .expect("generate contracts first")
                .replace("\r\n", "\n"),
            out,
            "contracts are stale"
        );
    } else {
        std::fs::write(path, out).unwrap();
    }
}
